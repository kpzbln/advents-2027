const fs = require("node:fs/promises");
const path = require("node:path");
const root = path.resolve(__dirname, "..");

async function collect(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collect(target));
    else if (/\.(webp|avif|svg|png)$/.test(entry.name)) {
      files.push(`./${path.relative(root, target).split(path.sep).join("/")}`);
    }
  }
  return files;
}

async function main() {
  const images = (await collect(path.join(root, "img"))).sort();
  await fs.writeFile(path.join(root, "offline-assets.js"),
    `// Generated by scripts/build-offline-assets.cjs.\nself.ADVENT_IMAGE_ASSETS = ${JSON.stringify(images, null, 2)};\n`);
  console.log(`Offline image manifest: ${images.length} files`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
